import { createEmptyThemePreset, type MarkdownWorkspaceThemeTokenMap, type ThemePreset } from "@mdwrk/theme-contract";
import type { ThemePackageArtifact } from "./types.js";

export interface ThemePackageMetadata {
  readonly themeId: string;
  readonly themeName: string;
  readonly packageName: string;
  readonly author: string;
  readonly description: string;
}

export function sanitizeThemeIdentifier(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "custom-theme";
}

export function sanitizePackageName(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) {
    return "@mdwrk/theme-custom-theme";
  }

  return trimmed
    .replace(/\s+/g, "-")
    .replace(/[^@a-z0-9._\/-]+/gi, "-")
    .replace(/--+/g, "-")
    .replace(/-+\//g, "/")
    .replace(/\/-+/g, "/");
}

export function buildThemePreset(
  metadata: ThemePackageMetadata,
  tokens: MarkdownWorkspaceThemeTokenMap,
): ThemePreset {
  const preset = createEmptyThemePreset(
    sanitizeThemeIdentifier(metadata.themeId),
    metadata.themeName.trim() || "Custom Theme",
  );

  return {
    ...preset,
    metadata: {
      ...preset.metadata,
      name: metadata.themeName.trim() || "Custom Theme",
      description: metadata.description.trim() || undefined,
      author: metadata.author.trim() || undefined,
      version: "1.0.1",
    },
    tokens,
  };
}

export function createThemePackageArtifact(
  preset: ThemePreset,
  css: { readonly host: string; readonly renderer: string; readonly editor: string },
  metadata: ThemePackageMetadata,
): ThemePackageArtifact {
  const packageName = sanitizePackageName(metadata.packageName);
  const themeId = sanitizeThemeIdentifier(preset.metadata.id);
  const packageJson = JSON.stringify({
    name: packageName,
    version: "0.1.0",
    type: "module",
    license: "Apache-2.0",
    description: preset.metadata.description ?? `Portable Markdown Workspace theme package for ${preset.metadata.name}.`,
    files: ["dist", "themes", "README.md"],
    style: "./dist/index.css",
    exports: {
      ".": "./dist/index.css",
      "./renderer.css": "./dist/renderer.css",
      "./editor.css": "./dist/editor.css",
      [`./themes/${themeId}.json`]: `./themes/${themeId}.json`,
    },
    keywords: ["markdown-workspace", "theme", "portable"],
  }, null, 2);

  const readme = [
    `# ${preset.metadata.name}`,
    "",
    preset.metadata.description ?? `Portable theme package scaffold generated by Theme Studio for ${preset.metadata.name}.`,
    "",
    "## Files",
    "",
    "- `dist/index.css` - host token CSS variables",
    "- `dist/renderer.css` - renderer bridge CSS variables",
    "- `dist/editor.css` - editor bridge CSS variables",
    `- \`themes/${themeId}.json\` - theme preset JSON`,
  ].join("\n");

  const json = JSON.stringify(preset, null, 2);
  return {
    packageName,
    files: [
      { path: "package.json", content: packageJson, mimeType: "application/json" },
      { path: "README.md", content: readme, mimeType: "text/markdown" },
      { path: "dist/index.css", content: css.host, mimeType: "text/css" },
      { path: "dist/renderer.css", content: css.renderer, mimeType: "text/css" },
      { path: "dist/editor.css", content: css.editor, mimeType: "text/css" },
      { path: `themes/${themeId}.json`, content: json, mimeType: "application/json" },
    ],
  };
}

export function parseThemePackageArtifact(payload: string): ThemePreset {
  const parsed = JSON.parse(payload) as { files?: Array<{ path?: string; content?: string }> };
  const themeFile = parsed.files?.find((entry) => typeof entry.path === "string" && entry.path.startsWith("themes/") && entry.path.endsWith(".json"));
  if (!themeFile?.content) {
    throw new Error("Theme package artifact is missing a themes/*.json preset payload.");
  }
  return JSON.parse(themeFile.content) as ThemePreset;
}
